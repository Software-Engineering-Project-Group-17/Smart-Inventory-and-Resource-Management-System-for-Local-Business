const WebSocket = require('ws');
const http = require('http');
const https = require('https');
const fs = require('fs');
const path = require('path');
const url = require('url');

class UserSession {
  constructor(userEmail) {
    this.userEmail = userEmail;
    this.connections = new Set();
    this.lastActivity = Date.now();
  }

  addConnection(ws) {
    this.connections.add(ws);
    this.lastActivity = Date.now();
    console.log(`Added connection for user: ${this.userEmail}. Total connections: ${this.connections.size}`);
  }

  removeConnection(ws) {
    this.connections.delete(ws);
    console.log(`Removed connection for user: ${this.userEmail}. Remaining connections: ${this.connections.size}`);
  }

  broadcastBarcode(barcodeData) {
    this.lastActivity = Date.now();
    const message = JSON.stringify({
      type: 'barcode',
      barcode: barcodeData.barcode,
      timestamp: barcodeData.timestamp || new Date().toISOString(),
      user: this.userEmail
    });

    console.log(`Broadcasting barcode to ${this.connections.size} connections for user: ${this.userEmail}`);

    this.connections.forEach(ws => {
      if (ws.readyState === WebSocket.OPEN) {
        try {
          ws.send(message);
          console.log(`Barcode sent to connection: ${barcodeData.barcode}`);
        } catch (error) {
          console.error('Error sending barcode to connection:', error);
          this.removeConnection(ws);
        }
      } else {
        this.removeConnection(ws);
      }
    });
  }

  isExpired() {
    return Date.now() - this.lastActivity > 30 * 60 * 1000; // 30 minutes
  }

  cleanup() {
    this.connections.forEach(ws => {
      if (ws.readyState === WebSocket.OPEN) {
        ws.close();
      }
    });
    this.connections.clear();
  }
}

class SecureBarcodeWebSocketServer {
  constructor() {
    this.userSessions = new Map();
    this.httpServer = http.createServer();
    this.httpsServer = null;
    this.wss = null;
    this.wsss = null; // Secure WebSocket Server

    this.setupWebSocketHandlers();
    this.startCleanupInterval();
  }

  createHttpsServer() {
    try {
      // Try to use the certificates generated by Next.js
      const certDir = path.join(__dirname, 'certificates');
      const keyPath = path.join(certDir, 'localhost-key.pem');
      const certPath = path.join(certDir, 'localhost.pem');

      if (fs.existsSync(keyPath) && fs.existsSync(certPath)) {
        const options = {
          key: fs.readFileSync(keyPath),
          cert: fs.readFileSync(certPath)
        };

        this.httpsServer = https.createServer(options);
        console.log('HTTPS server created with existing certificates');
        return true;
      } else {
        console.log('No certificates found at:', certDir);
        return false;
      }
    } catch (error) {
      console.error('Error creating HTTPS server:', error);
      return false;
    }
  }

  verifyClient(info) {
    try {
      const query = url.parse(info.req.url, true).query;
      const userEmail = query.user;
      
      if (!userEmail || typeof userEmail !== 'string') {
        console.log('WebSocket connection rejected: No user email provided');
        return false;
      }

      console.log(`WebSocket connection request from user: ${userEmail}`);
      return true;
    } catch (error) {
      console.error('Error verifying WebSocket client:', error);
      return false;
    }
  }

  setupWebSocketHandlers() {
    const handleConnection = (ws, request) => {
      try {
        const query = url.parse(request.url, true).query;
        const userEmail = query.user;

        if (!userEmail) {
          ws.close(1000, 'User email required');
          return;
        }

        // Get or create user session
        let session = this.userSessions.get(userEmail);
        if (!session) {
          session = new UserSession(userEmail);
          this.userSessions.set(userEmail, session);
          console.log(`Created new session for user: ${userEmail}`);
        }

        // Add connection to session
        session.addConnection(ws);

        // Set up message handler
        ws.on('message', (data) => {
          try {
            const message = JSON.parse(data.toString());
            console.log(`Received message from ${userEmail}:`, message);

            if (message.type === 'barcode' && message.barcode) {
              session.broadcastBarcode({
                barcode: message.barcode,
                timestamp: message.timestamp || new Date().toISOString()
              });
            } else if (message.type === 'ping') {
              ws.send(JSON.stringify({ type: 'pong', timestamp: new Date().toISOString() }));
            }
          } catch (error) {
            console.error('Error processing message:', error);
          }
        });

        // Handle connection close
        ws.on('close', () => {
          console.log(`WebSocket connection closed for user: ${userEmail}`);
          session.removeConnection(ws);

          // Remove session if no connections remain
          if (session.connections.size === 0) {
            this.userSessions.delete(userEmail);
            console.log(`Session removed for user: ${userEmail}`);
          }
        });

        // Handle connection errors
        ws.on('error', (error) => {
          console.error(`WebSocket error for user ${userEmail}:`, error);
          session.removeConnection(ws);
        });

        // Send connection confirmation
        ws.send(JSON.stringify({
          type: 'connected',
          message: 'WebSocket connection established',
          user: userEmail,
          timestamp: new Date().toISOString(),
          secure: request.connection.encrypted || false
        }));

        console.log(`WebSocket connection established for user: ${userEmail} (Secure: ${request.connection.encrypted || false})`);

      } catch (error) {
        console.error('Error handling WebSocket connection:', error);
        ws.close(1011, 'Internal server error');
      }
    };

    // Create HTTP WebSocket server
    this.wss = new WebSocket.Server({ 
      server: this.httpServer,
      verifyClient: this.verifyClient.bind(this)
    });

    this.wss.on('connection', handleConnection);

    this.wss.on('error', (error) => {
      console.error('WebSocket server error:', error);
    });

    // Create HTTPS WebSocket server if certificates are available
    if (this.createHttpsServer()) {
      this.wsss = new WebSocket.Server({ 
        server: this.httpsServer,
        verifyClient: this.verifyClient.bind(this)
      });

      this.wsss.on('connection', handleConnection);

      this.wsss.on('error', (error) => {
        console.error('Secure WebSocket server error:', error);
      });
    }
  }

  startCleanupInterval() {
    setInterval(() => {
      const expiredUsers = [];
      
      this.userSessions.forEach((session, userEmail) => {
        if (session.isExpired()) {
          expiredUsers.push(userEmail);
        }
      });

      expiredUsers.forEach(userEmail => {
        const session = this.userSessions.get(userEmail);
        if (session) {
          console.log(`Cleaning up expired session for user: ${userEmail}`);
          session.cleanup();
          this.userSessions.delete(userEmail);
        }
      });

      if (expiredUsers.length > 0) {
        console.log(`Cleaned up ${expiredUsers.length} expired sessions`);
      }
    }, 5 * 60 * 1000); // Check every 5 minutes
  }

  start(httpPort = 8080, httpsPort = 8443) {
    // Start HTTP WebSocket server
    this.httpServer.listen(httpPort, '0.0.0.0', () => {
      console.log(`HTTP WebSocket Server running on port ${httpPort}`);
      console.log(`WebSocket URL: ws://localhost:${httpPort}?user=<email>`);
      console.log(`Network WebSocket URL: ws://0.0.0.0:${httpPort}?user=<email>`);
    });

    // Start HTTPS WebSocket server if available
    if (this.httpsServer) {
      this.httpsServer.listen(httpsPort, '0.0.0.0', () => {
        console.log(`HTTPS WebSocket Server running on port ${httpsPort}`);
        console.log(`Secure WebSocket URL: wss://localhost:${httpsPort}?user=<email>`);
        console.log(`Network Secure WebSocket URL: wss://0.0.0.0:${httpsPort}?user=<email>`);
      });
    }

    console.log('Servers are ready to accept connections from any device on the network');

    // Graceful shutdown
    process.on('SIGINT', () => {
      console.log('\nShutting down WebSocket servers...');
      
      this.userSessions.forEach((session, userEmail) => {
        console.log(`Cleaning up session for user: ${userEmail}`);
        session.cleanup();
      });
      
      this.wss.close(() => {
        console.log('HTTP WebSocket server closed');
        
        if (this.wsss) {
          this.wsss.close(() => {
            console.log('HTTPS WebSocket server closed');
            process.exit(0);
          });
        } else {
          process.exit(0);
        }
      });
    });
  }

  // Method to get server status
  getStatus() {
    return {
      totalSessions: this.userSessions.size,
      totalConnections: Array.from(this.userSessions.values())
        .reduce((total, session) => total + session.connections.size, 0),
      activeSessions: Array.from(this.userSessions.entries()).map(([email, session]) => ({
        email,
        connections: session.connections.size,
        lastActivity: new Date(session.lastActivity).toISOString()
      })),
      httpServer: !!this.wss,
      httpsServer: !!this.wsss
    };
  }
}

// Start the server
const server = new SecureBarcodeWebSocketServer();
server.start(8080, 8443);

// Export for potential require usage
module.exports = SecureBarcodeWebSocketServer;