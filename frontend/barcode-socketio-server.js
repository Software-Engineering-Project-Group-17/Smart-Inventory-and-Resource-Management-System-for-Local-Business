const { Server } = require('socket.io');
const http = require('http');
const https = require('https');
const fs = require('fs');
const path = require('path');

class UserSession {
  constructor(userEmail) {
    this.userEmail = userEmail;
    this.sockets = new Set();
    this.lastActivity = Date.now();
  }

  addSocket(socket) {
    this.sockets.add(socket);
    this.lastActivity = Date.now();
    console.log(`Added socket for user: ${this.userEmail}. Total sockets: ${this.sockets.size}`);
  }

  removeSocket(socket) {
    this.sockets.delete(socket);
    console.log(`Removed socket for user: ${this.userEmail}. Remaining sockets: ${this.sockets.size}`);
  }

  broadcastBarcode(barcodeData) {
    this.lastActivity = Date.now();
    console.log(`Broadcasting barcode to ${this.sockets.size} sockets for user: ${this.userEmail}`);

    this.sockets.forEach(socket => {
      if (socket.connected) {
        try {
          socket.emit('barcode_scanned', {
            barcode: barcodeData.barcode,
            timestamp: barcodeData.timestamp || new Date().toISOString(),
            user: this.userEmail
          });
          console.log(`Barcode sent to socket: ${barcodeData.barcode}`);
        } catch (error) {
          console.error('Error sending barcode to socket:', error);
          this.removeSocket(socket);
        }
      } else {
        this.removeSocket(socket);
      }
    });
  }

  isExpired() {
    return Date.now() - this.lastActivity > 30 * 60 * 1000; // 30 minutes
  }

  cleanup() {
    this.sockets.forEach(socket => {
      if (socket.connected) {
        socket.disconnect();
      }
    });
    this.sockets.clear();
  }

  getConnectionCount() {
    return this.sockets.size;
  }
}

class SecureBarcodeSocketIOServer {
  constructor() {
    this.userSessions = new Map();
    this.httpServer = http.createServer();
    this.httpsServer = null;
    this.httpIO = null;
    this.httpsIO = null;

    this.setupServers();
    this.startCleanupInterval();
  }

  createHttpsServer() {
    try {
      // Try to use the certificates generated by Next.js
      const certDir = path.join(__dirname, 'certificates');
      const keyPath = path.join(certDir, 'localhost-key.pem');
      const certPath = path.join(certDir, 'localhost.pem');

      if (fs.existsSync(keyPath) && fs.existsSync(certPath)) {
        const options = {
          key: fs.readFileSync(keyPath),
          cert: fs.readFileSync(certPath)
        };

        this.httpsServer = https.createServer(options);
        console.log('HTTPS server created with existing certificates');
        return true;
      } else {
        console.log('No certificates found at:', certDir);
        return false;
      }
    } catch (error) {
      console.error('Error creating HTTPS server:', error);
      return false;
    }
  }

  setupServers() {
    // Setup HTTP Socket.IO server
    this.httpIO = new Server(this.httpServer, {
      cors: {
        origin: "*", // Configure this properly for production
        methods: ["GET", "POST"]
      },
      transports: ['websocket', 'polling'],
      allowEIO3: true
    });

    this.setupSocketHandlers(this.httpIO, false);

    // Setup HTTPS Socket.IO server if certificates are available
    if (this.createHttpsServer()) {
      this.httpsIO = new Server(this.httpsServer, {
        cors: {
          origin: "*", // Configure this properly for production
          methods: ["GET", "POST"]
        },
        transports: ['websocket', 'polling'],
        allowEIO3: true
      });

      this.setupSocketHandlers(this.httpsIO, true);
    }
  }

  setupSocketHandlers(io, isSecure) {
    io.on('connection', (socket) => {
      console.log(`New Socket.IO connection (Secure: ${isSecure}):`, socket.id);
      let userEmail = null;
      let userSession = null;

      // Handle authentication
      socket.on('user_auth', (data) => {
        try {
          userEmail = data.email || socket.handshake.query.user || socket.handshake.auth?.userEmail;
          
          if (!userEmail) {
            socket.emit('auth_error', { message: 'User email is required' });
            socket.disconnect();
            return;
          }

          console.log(`Authenticating user: ${userEmail}`);

          // Get or create user session
          userSession = this.userSessions.get(userEmail);
          if (!userSession) {
            userSession = new UserSession(userEmail);
            this.userSessions.set(userEmail, userSession);
            console.log(`Created new session for user: ${userEmail}`);
          }

          // Add socket to user session
          userSession.addSocket(socket);

          // Join user-specific room
          socket.join(`user_${userEmail}`);

          // Send authentication success
          socket.emit('auth_success', {
            message: 'Authentication successful',
            user: userEmail,
            activeConnections: userSession.getConnectionCount(),
            timestamp: new Date().toISOString()
          });

          // Notify all user's sockets about connection count update
          io.to(`user_${userEmail}`).emit('connection_update', {
            activeConnections: userSession.getConnectionCount()
          });

          console.log(`User ${userEmail} authenticated successfully`);

        } catch (error) {
          console.error('Error during authentication:', error);
          socket.emit('auth_error', { message: 'Authentication failed' });
        }
      });

      // Handle barcode scanning
      socket.on('barcode_scan', (data) => {
        try {
          if (!userEmail || !userSession) {
            socket.emit('scan_error', { message: 'User not authenticated' });
            return;
          }

          console.log(`Received barcode scan from ${userEmail}:`, data);

          if (data.barcode) {
            // Broadcast to all user's sockets (including other devices)
            userSession.broadcastBarcode({
              barcode: data.barcode,
              timestamp: data.timestamp || new Date().toISOString()
            });
          } else {
            socket.emit('scan_error', { message: 'Invalid barcode data' });
          }
        } catch (error) {
          console.error('Error processing barcode scan:', error);
          socket.emit('scan_error', { message: 'Failed to process barcode' });
        }
      });

      // Handle ping/heartbeat
      socket.on('ping', () => {
        socket.emit('pong', { timestamp: new Date().toISOString() });
      });

      // Handle manual disconnect
      socket.on('disconnect', (reason) => {
        console.log(`Socket.IO connection closed for ${userEmail || 'unknown user'}:`, reason);
        
        if (userSession && userEmail) {
          userSession.removeSocket(socket);

          // Update connection count for remaining sockets
          if (userSession.getConnectionCount() > 0) {
            io.to(`user_${userEmail}`).emit('connection_update', {
              activeConnections: userSession.getConnectionCount()
            });
          } else {
            // Remove session if no sockets remain
            this.userSessions.delete(userEmail);
            console.log(`Session removed for user: ${userEmail}`);
          }
        }
      });

      // Handle socket errors
      socket.on('error', (error) => {
        console.error(`Socket.IO error for user ${userEmail || 'unknown'}:`, error);
        if (userSession) {
          userSession.removeSocket(socket);
        }
      });

      // Auto-authenticate if user email is provided in handshake
      const initialEmail = socket.handshake.query.user || socket.handshake.auth?.userEmail;
      if (initialEmail) {
        console.log('Auto-authenticating user from handshake:', initialEmail);
        // Trigger authentication by directly handling the auth data
        userEmail = initialEmail;
        
        // Get or create user session
        userSession = this.userSessions.get(userEmail);
        if (!userSession) {
          userSession = new UserSession(userEmail);
          this.userSessions.set(userEmail, userSession);
          console.log(`Created new session for user: ${userEmail}`);
        }

        // Add socket to user session
        userSession.addSocket(socket);

        // Join user-specific room
        socket.join(`user_${userEmail}`);

        // Send authentication success
        socket.emit('auth_success', {
          message: 'Auto-authentication successful',
          user: userEmail,
          activeConnections: userSession.getConnectionCount(),
          timestamp: new Date().toISOString()
        });

        // Notify all user's sockets about connection count update
        io.to(`user_${userEmail}`).emit('connection_update', {
          activeConnections: userSession.getConnectionCount()
        });

        console.log(`User ${userEmail} auto-authenticated successfully`);
      }
    });

    io.on('error', (error) => {
      console.error(`Socket.IO server error (Secure: ${isSecure}):`, error);
    });
  }

  startCleanupInterval() {
    setInterval(() => {
      const expiredUsers = [];
      
      this.userSessions.forEach((session, userEmail) => {
        if (session.isExpired()) {
          expiredUsers.push(userEmail);
        }
      });

      expiredUsers.forEach(userEmail => {
        const session = this.userSessions.get(userEmail);
        if (session) {
          console.log(`Cleaning up expired session for user: ${userEmail}`);
          session.cleanup();
          this.userSessions.delete(userEmail);
        }
      });

      if (expiredUsers.length > 0) {
        console.log(`Cleaned up ${expiredUsers.length} expired sessions`);
      }
    }, 5 * 60 * 1000); // Check every 5 minutes
  }

  start(httpPort = 8080, httpsPort = 8443) {
    // Start HTTP Socket.IO server
    this.httpServer.listen(httpPort, '0.0.0.0', () => {
      console.log(`HTTP Socket.IO Server running on port ${httpPort}`);
      console.log(`Socket.IO URL: http://localhost:${httpPort}`);
      console.log(`Network Socket.IO URL: http://0.0.0.0:${httpPort}`);
    });

    // Start HTTPS Socket.IO server if available
    if (this.httpsServer && this.httpsIO) {
      this.httpsServer.listen(httpsPort, '0.0.0.0', () => {
        console.log(`HTTPS Socket.IO Server running on port ${httpsPort}`);
        console.log(`Secure Socket.IO URL: https://localhost:${httpsPort}`);
        console.log(`Network Secure Socket.IO URL: https://0.0.0.0:${httpsPort}`);
      });
    }

    console.log('Socket.IO servers are ready to accept connections from any device on the network');

    // Graceful shutdown
    process.on('SIGINT', () => {
      console.log('\nShutting down Socket.IO servers...');
      
      this.userSessions.forEach((session, userEmail) => {
        console.log(`Cleaning up session for user: ${userEmail}`);
        session.cleanup();
      });
      
      if (this.httpIO) {
        this.httpIO.close(() => {
          console.log('HTTP Socket.IO server closed');
        });
      }

      if (this.httpsIO) {
        this.httpsIO.close(() => {
          console.log('HTTPS Socket.IO server closed');
        });
      }

      setTimeout(() => {
        process.exit(0);
      }, 1000);
    });
  }

  // Method to get server status
  getStatus() {
    return {
      totalSessions: this.userSessions.size,
      totalConnections: Array.from(this.userSessions.values())
        .reduce((total, session) => total + session.getConnectionCount(), 0),
      activeSessions: Array.from(this.userSessions.entries()).map(([email, session]) => ({
        email,
        connections: session.getConnectionCount(),
        lastActivity: new Date(session.lastActivity).toISOString()
      })),
      httpServer: !!this.httpIO,
      httpsServer: !!this.httpsIO
    };
  }
}

// Start the server
const server = new SecureBarcodeSocketIOServer();
server.start(8080, 8443);

// Export for potential require usage
module.exports = SecureBarcodeSocketIOServer;