-- Restock request summary view
CREATE OR REPLACE VIEW restock_request_summary_view AS
SELECT 
    rr.id as request_id,
    rr.title,
    rr.status,
    rr.priority,
    rr.created_at,
    rr.required_by_date,
    rr.total_estimated_cost,
    
    -- Branch details
    b.name as branch_name,
    b.location as branch_location,
    
    -- Creator details
    u.name as created_by_name,
    u.email as created_by_email,
    
    -- Request statistics
    COUNT(rri.id) as total_items_requested,
    SUM(rri.requested_quantity) as total_quantity_requested,
    COUNT(DISTINCT so.id) as supplier_orders_count,
    COUNT(CASE WHEN so.payment_status = 'paid' THEN 1 END) as paid_orders_count,
    SUM(CASE WHEN so.payment_status = 'paid' THEN so.total_amount ELSE 0 END) as total_paid_amount
    
FROM restock_request rr
LEFT JOIN branches b ON rr.branch_id = b.id
LEFT JOIN "user" u ON rr.created_by = u.user_id
LEFT JOIN restock_request_item rri ON rr.id = rri.restock_request_id
LEFT JOIN supplier_order so ON rr.id = so.restock_request_id
GROUP BY rr.id, rr.title, rr.status, rr.priority, rr.created_at, rr.required_by_date, rr.total_estimated_cost, b.name, b.location, u.name, u.email;

-- Supplier order details view
CREATE OR REPLACE VIEW supplier_order_details_view AS
SELECT 
    so.id as order_id,
    so.order_status,
    so.payment_status,
    so.total_amount,
    so.created_at,
    so.estimated_delivery_date,
    so.actual_delivery_date,
    
    -- Restock request details
    rr.id as request_id,
    rr.title as request_title,
    rr.priority as request_priority,
    
    -- Branch details
    b.name as branch_name,
    b.location as branch_location,
    
    -- Supplier details
    s.supplier_name,
    s.supplier_email,
    s.supplier_tel,
    
    -- Order statistics
    COUNT(soi.id) as items_count,
    SUM(soi.offered_quantity) as total_quantity_offered
    
FROM supplier_order so
LEFT JOIN restock_request rr ON so.restock_request_id = rr.id
LEFT JOIN branches b ON rr.branch_id = b.id
LEFT JOIN supplier s ON so.supplier_id = s.id
LEFT JOIN supplier_order_item soi ON so.id = soi.supplier_order_id
GROUP BY so.id, so.order_status, so.payment_status, so.total_amount, so.created_at, so.estimated_delivery_date, so.actual_delivery_date, rr.id, rr.title, rr.priority, b.name, b.location, s.supplier_name, s.supplier_email, s.supplier_tel;

-- Inventory restock tracking view
CREATE OR REPLACE VIEW inventory_restock_tracking_view AS
SELECT 
    ii.inventory_id,
    ii.inventory_name,
    ii.quantity as current_stock,
    ii.low_stock_threshold,
    
    -- Branch details
    b.name as branch_name,
    
    -- Category details
    c.category_name,
    
    -- Active restock requests for this item
    COUNT(DISTINCT rri.restock_request_id) as active_restock_requests,
    SUM(rri.requested_quantity) as total_requested_quantity,
    
    -- Supplier orders for this item
    COUNT(DISTINCT soi.supplier_order_id) as supplier_orders_count,
    SUM(CASE WHEN so.payment_status = 'paid' THEN soi.offered_quantity ELSE 0 END) as paid_incoming_quantity,
    SUM(CASE WHEN so.order_status = 'pending' AND so.payment_status = 'unpaid' THEN soi.offered_quantity ELSE 0 END) as pending_incoming_quantity
    
FROM inventory_item ii
LEFT JOIN branches b ON ii.branch_id = b.id
LEFT JOIN category c ON ii.category_id = c.id
LEFT JOIN restock_request_item rri ON ii.inventory_id = rri.inventory_id
LEFT JOIN restock_request rr ON rri.restock_request_id = rr.id AND rr.status IN ('pending', 'active')
LEFT JOIN supplier_order_item soi ON rri.id = soi.restock_request_item_id
LEFT JOIN supplier_order so ON soi.supplier_order_id = so.id
GROUP BY ii.inventory_id, ii.inventory_name, ii.quantity, ii.low_stock_threshold, b.name, c.category_name;

