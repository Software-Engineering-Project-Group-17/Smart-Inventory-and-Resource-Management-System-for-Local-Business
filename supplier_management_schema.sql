-- 1. Restock Request Table (Staff/Branch Manager creates these)
CREATE TABLE IF NOT EXISTS restock_request (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    branch_id BIGINT NOT NULL,
    created_by BIGINT NOT NULL, -- Staff/Branch Manager who created the request
    title VARCHAR(255) NOT NULL,
    description TEXT,
    status restock_request_status NOT NULL DEFAULT 'pending',
    total_estimated_cost NUMERIC(12,2) DEFAULT 0,
    priority VARCHAR(20) DEFAULT 'normal' CHECK (priority IN ('low', 'normal', 'high', 'urgent')),
    required_by_date DATE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
    completed_at TIMESTAMP WITH TIME ZONE,
    notes TEXT,
    
    CONSTRAINT restock_request_branch_id_fkey FOREIGN KEY (branch_id) REFERENCES branches(id) ON DELETE CASCADE,
    CONSTRAINT restock_request_created_by_fkey FOREIGN KEY (created_by) REFERENCES "user"(user_id) ON DELETE CASCADE,
    CONSTRAINT restock_request_total_estimated_cost_check CHECK (total_estimated_cost >= 0::numeric)
);

-- 2. Restock Request Items Table (Items in the restock cart)
CREATE TABLE IF NOT EXISTS restock_request_item (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    restock_request_id BIGINT NOT NULL,
    inventory_id BIGINT NOT NULL, -- Reference to inventory_item
    requested_quantity INTEGER NOT NULL,
    estimated_unit_price NUMERIC(12,2), -- Estimated price for budgeting
    notes TEXT, -- Special requirements for this item
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
    
    CONSTRAINT restock_request_item_restock_request_id_fkey FOREIGN KEY (restock_request_id) REFERENCES restock_request(id) ON DELETE CASCADE,
    CONSTRAINT restock_request_item_inventory_id_fkey FOREIGN KEY (inventory_id) REFERENCES inventory_item(inventory_id) ON DELETE CASCADE,
    CONSTRAINT restock_request_item_requested_quantity_check CHECK (requested_quantity > 0),
    CONSTRAINT restock_request_item_estimated_unit_price_check CHECK (estimated_unit_price >= 0::numeric),
    CONSTRAINT restock_request_item_unique UNIQUE (restock_request_id, inventory_id)
);

-- ========================================
-- STEP 3: ENHANCE EXISTING SUPPLIER TABLES
-- ========================================

-- Drop the current supplier_order table to recreate it with proper structure
DROP TABLE IF EXISTS supplier_order CASCADE;

-- Enhanced Supplier Order Table (Suppliers create these in response to restock requests)
CREATE TABLE IF NOT EXISTS supplier_order (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    restock_request_id BIGINT NOT NULL, -- Links to the restock request
    supplier_id BIGINT NOT NULL,
    order_status order_status NOT NULL DEFAULT 'pending',
    payment_status supplier_payment_status NOT NULL DEFAULT 'unpaid',
    total_amount NUMERIC(12,2) NOT NULL DEFAULT 0,
    estimated_delivery_date DATE,
    actual_delivery_date DATE,
    supplier_notes TEXT,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
    paid_at TIMESTAMP WITH TIME ZONE,
    cancelled_at TIMESTAMP WITH TIME ZONE,
    
    -- Payment integration fields
    stripe_payment_intent_id VARCHAR(255),
    payment_method VARCHAR(50) DEFAULT 'stripe',
    
    CONSTRAINT supplier_order_restock_request_id_fkey FOREIGN KEY (restock_request_id) REFERENCES restock_request(id) ON DELETE CASCADE,
    CONSTRAINT supplier_order_supplier_id_fkey FOREIGN KEY (supplier_id) REFERENCES supplier(id) ON DELETE CASCADE,
    CONSTRAINT supplier_order_total_amount_check CHECK (total_amount >= 0::numeric)
);

-- 3. Supplier Order Items Table (Individual items in supplier orders with pricing)
CREATE TABLE IF NOT EXISTS supplier_order_item (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    supplier_order_id BIGINT NOT NULL,
    restock_request_item_id BIGINT NOT NULL, -- Links to the specific requested item
    inventory_id BIGINT NOT NULL, -- Reference to inventory_item
    supplier_item_name VARCHAR(255), -- Supplier's name for the item (might differ)
    offered_quantity INTEGER NOT NULL,
    unit_price NUMERIC(12,2) NOT NULL,
    total_price NUMERIC(12,2) NOT NULL,
    supplier_item_description TEXT,
    availability_status VARCHAR(50) DEFAULT 'available' CHECK (availability_status IN ('available', 'limited', 'out_of_stock', 'discontinued')),
    lead_time_days INTEGER DEFAULT 0,
    
    CONSTRAINT supplier_order_item_supplier_order_id_fkey FOREIGN KEY (supplier_order_id) REFERENCES supplier_order(id) ON DELETE CASCADE,
    CONSTRAINT supplier_order_item_restock_request_item_id_fkey FOREIGN KEY (restock_request_item_id) REFERENCES restock_request_item(id) ON DELETE CASCADE,
    CONSTRAINT supplier_order_item_inventory_id_fkey FOREIGN KEY (inventory_id) REFERENCES inventory_item(inventory_id) ON DELETE CASCADE,
    CONSTRAINT supplier_order_item_offered_quantity_check CHECK (offered_quantity > 0),
    CONSTRAINT supplier_order_item_unit_price_check CHECK (unit_price >= 0::numeric),
    CONSTRAINT supplier_order_item_total_price_check CHECK (total_price >= 0::numeric),
    CONSTRAINT supplier_order_item_lead_time_check CHECK (lead_time_days >= 0),
    CONSTRAINT supplier_order_item_unique UNIQUE (supplier_order_id, restock_request_item_id)
);

-- 4. Enhance supplier_item table to include capabilities
DROP TABLE IF EXISTS supplier_item CASCADE;

CREATE TABLE IF NOT EXISTS supplier_item (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    supplier_id BIGINT NOT NULL,
    inventory_id BIGINT, -- Link to specific inventory items they can supply
    supplier_item_name VARCHAR(255) NOT NULL, -- Supplier's name for the item
    category_id BIGINT, -- Category they specialize in
    base_unit_price NUMERIC(12,2), -- Their standard price
    minimum_order_quantity INTEGER DEFAULT 1,
    maximum_order_quantity INTEGER,
    lead_time_days INTEGER DEFAULT 0,
    is_active BOOLEAN DEFAULT true,
    description TEXT,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
    
    CONSTRAINT supplier_item_supplier_id_fkey FOREIGN KEY (supplier_id) REFERENCES supplier(id) ON DELETE CASCADE,
    CONSTRAINT supplier_item_inventory_id_fkey FOREIGN KEY (inventory_id) REFERENCES inventory_item(inventory_id) ON DELETE SET NULL,
    CONSTRAINT supplier_item_category_id_fkey FOREIGN KEY (category_id) REFERENCES category(id) ON DELETE SET NULL,
    CONSTRAINT supplier_item_base_unit_price_check CHECK (base_unit_price >= 0::numeric),
    CONSTRAINT supplier_item_minimum_order_quantity_check CHECK (minimum_order_quantity > 0),
    CONSTRAINT supplier_item_maximum_order_quantity_check CHECK (maximum_order_quantity IS NULL OR maximum_order_quantity >= minimum_order_quantity),
    CONSTRAINT supplier_item_lead_time_check CHECK (lead_time_days >= 0)
);

-- 5. Supplier Payment Table (Track payments to suppliers)
CREATE TABLE IF NOT EXISTS supplier_payment (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    supplier_order_id BIGINT NOT NULL,
    amount NUMERIC(12,2) NOT NULL,
    payment_method VARCHAR(50) DEFAULT 'stripe',
    stripe_payment_intent_id VARCHAR(255),
    stripe_charge_id VARCHAR(255),
    payment_status supplier_payment_status NOT NULL DEFAULT 'unpaid',
    processed_at TIMESTAMP WITH TIME ZONE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
    metadata JSONB,
    transaction_id TEXT UNIQUE,
    
    CONSTRAINT supplier_payment_supplier_order_id_fkey FOREIGN KEY (supplier_order_id) REFERENCES supplier_order(id) ON DELETE CASCADE,
    CONSTRAINT supplier_payment_amount_check CHECK (amount >= 0::numeric)
);

