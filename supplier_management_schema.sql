-- Function to update supplier order total when items change
CREATE OR REPLACE FUNCTION update_supplier_order_total()
RETURNS TRIGGER AS $$
BEGIN
    UPDATE supplier_order 
    SET total_amount = (
        SELECT COALESCE(SUM(total_price), 0)
        FROM supplier_order_item 
        WHERE supplier_order_id = COALESCE(NEW.supplier_order_id, OLD.supplier_order_id)
    ),
    updated_at = now()
    WHERE id = COALESCE(NEW.supplier_order_id, OLD.supplier_order_id);
    
    RETURN COALESCE(NEW, OLD);
END;
$$ LANGUAGE plpgsql;

-- Trigger for supplier order items
DROP TRIGGER IF EXISTS trigger_update_supplier_order_total ON supplier_order_item;
CREATE TRIGGER trigger_update_supplier_order_total
    AFTER INSERT OR UPDATE OR DELETE ON supplier_order_item
    FOR EACH ROW
    EXECUTE FUNCTION update_supplier_order_total();

-- Function to update restock request estimated cost
CREATE OR REPLACE FUNCTION update_restock_request_estimated_cost()
RETURNS TRIGGER AS $$
BEGIN
    UPDATE restock_request 
    SET total_estimated_cost = (
        SELECT COALESCE(SUM(requested_quantity * COALESCE(estimated_unit_price, 0)), 0)
        FROM restock_request_item 
        WHERE restock_request_id = COALESCE(NEW.restock_request_id, OLD.restock_request_id)
    ),
    updated_at = now()
    WHERE id = COALESCE(NEW.restock_request_id, OLD.restock_request_id);
    
    RETURN COALESCE(NEW, OLD);
END;
$$ LANGUAGE plpgsql;

-- Trigger for restock request items
DROP TRIGGER IF EXISTS trigger_update_restock_request_estimated_cost ON restock_request_item;
CREATE TRIGGER trigger_update_restock_request_estimated_cost
    AFTER INSERT OR UPDATE OR DELETE ON restock_request_item
    FOR EACH ROW
    EXECUTE FUNCTION update_restock_request_estimated_cost();

-- Function to update inventory after successful supplier payment
CREATE OR REPLACE FUNCTION update_inventory_after_supplier_payment()
RETURNS TRIGGER AS $$
BEGIN
    -- Only update inventory when payment status changes to 'paid'
    IF NEW.payment_status = 'paid' AND OLD.payment_status != 'paid' THEN
        -- Update inventory quantities for all items in this supplier order
        UPDATE inventory_item 
        SET quantity = quantity + soi.offered_quantity
        FROM supplier_order_item soi
        WHERE soi.supplier_order_id = NEW.id 
        AND inventory_item.inventory_id = soi.inventory_id;
        
        -- Update the payment timestamp
        NEW.paid_at = now();
    END IF;
    
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

-- Trigger for supplier order payment updates
DROP TRIGGER IF EXISTS trigger_update_inventory_after_supplier_payment ON supplier_order;
CREATE TRIGGER trigger_update_inventory_after_supplier_payment
    BEFORE UPDATE ON supplier_order
    FOR EACH ROW
    EXECUTE FUNCTION update_inventory_after_supplier_payment();

