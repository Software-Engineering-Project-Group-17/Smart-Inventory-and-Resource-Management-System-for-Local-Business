-- Create a view for easy resource querying with assignment details
CREATE OR REPLACE VIEW resource_with_assignment_view AS
SELECT 
    r.id,
    r.name,
    r.resource_number,
    r.description,
    r.resource_type,
    r.availability_status,
    r.branch_id,
    r.created_at,
    r.updated_at,
    r.created_by,
    
    -- Current assignment details
    sra.id as assignment_id,
    sra.purpose,
    sra.start_date,
    sra.end_date,
    sra.start_time,
    sra.end_time,
    sra.assigned_at,
    
    -- Staff details
    s.id as staff_id,
    s.first_name,
    s.last_name,
    s.email as staff_email,
    s.tel as staff_phone,
    
    -- Branch details
    b.name as branch_name,
    b.location as branch_location
    
FROM resource r
LEFT JOIN staff_resource_assignment sra ON r.id = sra.resource_id AND sra.is_active = true
LEFT JOIN staff s ON sra.staff_id = s.id
LEFT JOIN branches b ON r.branch_id = b.id;

-- Create indexes for better performance
