CREATE INDEX IF NOT EXISTS idx_staff_resource_assignment_dates ON staff_resource_assignment(start_date, end_date);
CREATE INDEX IF NOT EXISTS idx_staff_resource_assignment_active ON staff_resource_assignment(is_active);

-- Add triggers for updated_at timestamp
CREATE OR REPLACE FUNCTION update_updated_at_column()
RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = now();
    RETURN NEW;
END;
$$ language 'plpgsql';

-- Create trigger for resource table
DROP TRIGGER IF EXISTS update_resource_updated_at ON resource;
CREATE TRIGGER update_resource_updated_at
    BEFORE UPDATE ON resource
    FOR EACH ROW
    EXECUTE FUNCTION update_updated_at_column();

